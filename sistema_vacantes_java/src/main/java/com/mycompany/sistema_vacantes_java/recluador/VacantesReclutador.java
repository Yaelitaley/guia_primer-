    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        javax.swing.JTextField trabajoField = new javax.swing.JTextField();
        javax.swing.JTextField categoriaField = new javax.swing.JTextField();
        javax.swing.JTextField salarioField = new javax.swing.JTextField();
        javax.swing.JComboBox<String> estadoCombo = new javax.swing.JComboBox<>(new String[]{"Activa", "Cerrada"});

        Object[] formulario = {
            "Puesto:", trabajoField,
            "Categoría:", categoriaField,
            "Salario:", salarioField,
            "Estado:", estadoCombo
        };

        int opcion = javax.swing.JOptionPane.showConfirmDialog(this, formulario, "Nueva Vacante", javax.swing.JOptionPane.OK_CANCEL_OPTION);

        if (opcion == javax.swing.JOptionPane.OK_OPTION) {
            String trabajo = trabajoField.getText().trim();
            String categoria = categoriaField.getText().trim();
            String salarioTexto = salarioField.getText().trim();

            if (trabajo.isEmpty() || salarioTexto.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El puesto y el salario son obligatorios.", "Campos incompletos", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            try {
                double salario = Double.parseDouble(salarioTexto.replace(",", ""));

                Connection con = ConexionBD.conectar();
                String sql = "INSERT INTO vacantes (trabajo, categoria, salario, estado) VALUES (?, ?, ?, ?)";
                PreparedStatement ps = con.prepareStatement(sql);
                ps.setString(1, trabajo);
                ps.setString(2, categoria.isEmpty() ? null : categoria);
                ps.setDouble(3, salario);
                ps.setString(4, (String) estadoCombo.getSelectedItem());
                ps.executeUpdate();
                ps.close();
                con.close();

                javax.swing.JOptionPane.showMessageDialog(this, "Vacante creada correctamente.");
                cargarVacantes(null, null);
                cargarEstadisticas();

            } catch (NumberFormatException nfe) {
                javax.swing.JOptionPane.showMessageDialog(this, "El salario debe ser un número.", "Dato inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo crear la vacante.\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

