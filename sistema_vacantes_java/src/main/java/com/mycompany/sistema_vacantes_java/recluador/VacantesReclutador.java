    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una vacante de la lista para borrarla.", "Sin selección", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = (int) jTable1.getValueAt(fila, 0);
        String trabajo = String.valueOf(jTable1.getValueAt(fila, 1));

        int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, "¿Seguro que deseas borrar la vacante \"" + trabajo + "\"?\nTambién se borrarán sus postulaciones.", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
            try {
                Connection con = ConexionBD.conectar();
                PreparedStatement ps = con.prepareStatement("DELETE FROM vacantes WHERE id = ?");
                ps.setInt(1, id);
                ps.executeUpdate();
                ps.close();
                con.close();

                javax.swing.JOptionPane.showMessageDialog(this, "Vacante eliminada.");
                cargarVacantes(null, null);
                cargarEstadisticas();
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo borrar la vacante.\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    private void cargarVacantes(String filtroTexto, String filtroEstado) {
        try {
            Connection con = ConexionBD.conectar();
            StringBuilder sql = new StringBuilder("SELECT id, trabajo, categoria, salario, estado FROM vacantes WHERE 1=1");

            if (filtroTexto != null) {
                sql.append(" AND (trabajo LIKE ? OR categoria LIKE ?)");
            }
            if (filtroEstado != null) {
                sql.append(" AND estado = ?");
            }
            sql.append(" ORDER BY id DESC");

            PreparedStatement ps = con.prepareStatement(sql.toString());
            int idx = 1;
            if (filtroTexto != null) {
                ps.setString(idx++, "%" + filtroTexto + "%");
                ps.setString(idx++, "%" + filtroTexto + "%");
            }
            if (filtroEstado != null) {
                ps.setString(idx++, filtroEstado);
            }

            ResultSet rs = ps.executeQuery();

            DefaultTableModel modelo = new DefaultTableModel(
                    new Object[]{"ID", "Puesto", "Categoría", "Salario", "Estado"}, 0);

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("trabajo"),
                    rs.getString("categoria"),
                    rs.getDouble("salario"),
                    rs.getString("estado")
                });
            }

            jTable1.setModel(modelo);

            rs.close();
            ps.close();
            con.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudieron cargar las vacantes.\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarEstadisticas() {
        try {
            Connection con = ConexionBD.conectar();

            PreparedStatement ps1 = con.prepareStatement("SELECT COUNT(*) FROM vacantes WHERE estado = 'Activa'");
            ResultSet rs1 = ps1.executeQuery();
            if (rs1.next()) jLabel3.setText(String.valueOf(rs1.getInt(1)));
            rs1.close();
            ps1.close();

            PreparedStatement ps2 = con.prepareStatement("SELECT COUNT(*) FROM vacantes WHERE estado <> 'Activa'");
            ResultSet rs2 = ps2.executeQuery();
            if (rs2.next()) jLabel5.setText(String.valueOf(rs2.getInt(1)));
            rs2.close();
            ps2.close();

            PreparedStatement ps3 = con.prepareStatement("SELECT COUNT(*) FROM postulaciones");
            ResultSet rs3 = ps3.executeQuery();
            if (rs3.next()) jLabel7.setText(String.valueOf(rs3.getInt(1)));
            rs3.close();
            ps3.close();

            PreparedStatement ps4 = con.prepareStatement("SELECT COUNT(DISTINCT categoria) FROM vacantes WHERE categoria IS NOT NULL");
            ResultSet rs4 = ps4.executeQuery();
            if (rs4.next()) jLabel9.setText(String.valueOf(rs4.getInt(1)));
            rs4.close();
            ps4.close();

            con.close();
        } catch (Exception e) {
            System.out.println(e.getMessage());
        }
    }

