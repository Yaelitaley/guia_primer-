    private void cargarPerfil() {
        try {
            Connection con = ConexionBD.conectar();
            PreparedStatement ps = con.prepareStatement("SELECT nombre, correo, telefono, ubicacion FROM reclutadores WHERE id = ?");
            ps.setInt(1, Sesion.reclutadorId);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                jTextField1.setText(rs.getString("nombre"));
                jTextField2.setText(rs.getString("correo"));
                jTextField3.setText(rs.getString("telefono"));
                jTextField4.setText(rs.getString("ubicacion"));
            }
            rs.close();
            ps.close();
            con.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo cargar tu perfil.\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

