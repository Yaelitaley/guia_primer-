    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText().trim();
        String correo = jTextField2.getText().trim();
        String telefono = jTextField3.getText().trim();
        String ubicacion = jTextField4.getText().trim();

        if (nombre.isEmpty() || correo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre y el correo son obligatorios.", "Campos incompletos", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection con = ConexionBD.conectar();
            PreparedStatement ps = con.prepareStatement(
                    "UPDATE reclutadores SET nombre = ?, correo = ?, telefono = ?, ubicacion = ? WHERE id = ?");
            ps.setString(1, nombre);
            ps.setString(2, correo);
            ps.setString(3, telefono.isEmpty() ? null : telefono);
            ps.setString(4, ubicacion.isEmpty() ? null : ubicacion);
            ps.setInt(5, Sesion.reclutadorId);
            ps.executeUpdate();
            ps.close();
            con.close();

            Sesion.reclutadorNombre = nombre;
            Sesion.reclutadorCorreo = correo;

            javax.swing.JOptionPane.showMessageDialog(this, "Perfil actualizado correctamente.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar tu perfil.\n" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

