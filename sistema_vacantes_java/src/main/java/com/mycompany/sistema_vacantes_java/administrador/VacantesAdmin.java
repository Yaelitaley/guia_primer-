    private void cargarCategorias() {
    jComboBox2.removeAllItems();
    jComboBox2.addItem("Todas las categorias");
    try {
        Connection con = ConexionBD.conectar();
        String sql = "SELECT DISTINCT categoria FROM vacantes WHERE categoria IS NOT NULL ORDER BY categoria";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();
        while (rs.next()) { jComboBox2.addItem(rs.getString("categoria")); }
        rs.close(); ps.close(); con.close();
    } catch (Exception e) { System.out.println(e.getMessage()); }
}

  private void cargarVacantes() {
    String estadoFiltro = jComboBox1.getSelectedItem() != null ? jComboBox1.getSelectedItem().toString() : "Todas las vacantes";
    String categoriaFiltro = jComboBox2.getSelectedItem() != null ? jComboBox2.getSelectedItem().toString() : "Todas las categorias";
    String texto = jTextField1.getText().trim();

    DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID");
    modelo.addColumn("Trabajo");
    modelo.addColumn("Categoria");
    modelo.addColumn("Salario");
    modelo.addColumn("Estado");

    StringBuilder sql = new StringBuilder("SELECT * FROM vacantes WHERE 1=1");
    if (!estadoFiltro.equals("Todas las vacantes")) sql.append(" AND estado = ?");
    if (!categoriaFiltro.equals("Todas las categorias")) sql.append(" AND categoria = ?");
    if (!texto.isEmpty()) sql.append(" AND trabajo LIKE ?");

    try {
        Connection con = ConexionBD.conectar();
        PreparedStatement ps = con.prepareStatement(sql.toString());
        int indice = 1;
        if (!estadoFiltro.equals("Todas las vacantes")) ps.setString(indice++, estadoFiltro);
        if (!categoriaFiltro.equals("Todas las categorias")) ps.setString(indice++, categoriaFiltro);
        if (!texto.isEmpty()) ps.setString(indice++, "%" + texto + "%");

        ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            Object fila[] = { rs.getInt("id"), rs.getString("trabajo"), rs.getString("categoria"), rs.getDouble("salario"), rs.getString("estado") };
            modelo.addRow(fila);
        }
        jTable2.setModel(modelo);
        rs.close(); ps.close(); con.close();
    } catch (Exception e) { System.out.println(e.getMessage()); }
}
    
    
    
    
    
    
    
    
