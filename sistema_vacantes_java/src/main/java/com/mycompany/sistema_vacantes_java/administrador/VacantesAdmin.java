    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    javax.swing.JTextField campoTrabajo = new javax.swing.JTextField();
    javax.swing.JTextField campoCategoria = new javax.swing.JTextField();
    javax.swing.JTextField campoSalario = new javax.swing.JTextField();
    javax.swing.JComboBox<String> campoEstado = new javax.swing.JComboBox<>(new String[]{"Activo", "Inactivo"});

    Object[] mensaje = {
        "Puesto de trabajo:", campoTrabajo,
        "Categoria:", campoCategoria,
        "Salario:", campoSalario,
        "Estado:", campoEstado
    };

    int opcion = JOptionPane.showConfirmDialog(this, mensaje, "Nueva Vacante", JOptionPane.OK_CANCEL_OPTION);
    if (opcion != JOptionPane.OK_OPTION) return;

    String trabajo = campoTrabajo.getText().trim();
    String categoria = campoCategoria.getText().trim();
    String salarioTexto = campoSalario.getText().trim();
    String estado = campoEstado.getSelectedItem().toString();

    if (trabajo.isEmpty() || categoria.isEmpty() || salarioTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, rellene todos los campos.", "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    double salario;
    try {
        salario = Double.parseDouble(salarioTexto);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El salario debe ser un número válido.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        Connection con = ConexionBD.conectar();
        String sql = "INSERT INTO vacantes (trabajo, categoria, salario, estado) VALUES (?, ?, ?, ?)";
        PreparedStatement ps = con.prepareStatement(sql);
        ps.setString(1, trabajo);
        ps.setString(2, categoria);
        ps.setDouble(3, salario);
        ps.setString(4, estado);
        ps.executeUpdate();
        ps.close();
        con.close();

        JOptionPane.showMessageDialog(this, "Vacante registrada con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        cargarCategorias();
        cargarVacantes();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "No se pudo registrar la vacante.\n" + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_jButton1ActionPerformed

